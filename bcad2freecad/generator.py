            f'make_tube("{t.name}",\n'
            f"    start=({s[0]:.2f}, {s[1]:.2f}, {s[2]:.2f}),\n"
            f"    end=({e[0]:.2f}, {e[1]:.2f}, {e[2]:.2f}),\n"
            f"    r1={t.radius1:.2f}, r2={t.radius2:.2f},\n"
